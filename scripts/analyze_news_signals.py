# 中性：纯市场数据/资讯、无明确方向
NEUTRAL_HINTS = ["资金流向日报", "龙虎榜数据", "行业.*资金", "盘中播报", "行情", "收评", "午盘", "盘初", "盘后", "名单出炉", "名单", "排行榜", "榜单", "播报"]

def classify(title):
    # ---- 特定跨标的误报修正（仅依据标题文本判断） ----
    # 白酒反弹但“科技股跳水”与之无关 -> 中性
    if "科技股却突发跳水" in title:
        return "HOLD", 0.5, "中性：白酒反弹，文中跳水指科技股，与标的无直接关系"
    # 特斯拉大跌但比亚迪成全球销冠 -> 利好（大跌指特斯拉）
    if "特斯拉" in title and "全球销冠" in title:
        return "BUY", 0.7, "利好：比亚迪再成纯电车全球销冠（文中大跌指特斯拉）"

    # 先判利空（利空优先级高，避免被利好词误判）
    for pat, conf, reason in SELL_RULES:
        if re.search(pat, title):
            return "SELL", conf, reason
    for pat, conf, reason in BUY_RULES:
        if re.search(pat, title):
            return "BUY", conf, reason
    return "HOLD", 0.5, "中性：无明显方向性新闻/市场资讯"

def main():
    with open(JSON, encoding="utf-8") as f:
        data = json.load(f)["signals"]
    conn = sqlite3.connect(DB)
    c = conn.cursor()
    counts = {"BUY": 0, "SELL": 0, "HOLD": 0}
    for s in data:
        sid = s["id"]
        action, conf, reason = classify(s["title"])
        counts[action] += 1
        c.execute(
            "UPDATE strategy_shadow_signals SET signal_action=?, confidence=?, signal_reason=? WHERE id=?",
            (action, conf, reason, sid),
        )
    conn.commit()
    conn.close()
    print("更新完成 -> 利好(BUY):%d 利空(SELL):%d 中性(HOLD):%d 总计:%d" % (
        counts["BUY"], counts["SELL"], counts["HOLD"], sum(counts.values())))
    return counts

if __name__ == "__main__":
    main()
